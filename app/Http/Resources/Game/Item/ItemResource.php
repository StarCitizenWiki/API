class ItemResource extends AbstractBaseResource
{
    use ExpandsUexPrices;
    use ExtractsJsonData;
    use ResolvesGameVersion;

    public function toArray(Request $request): array
    {
        if ($this->item?->uuid === null) {
            return [];
        }

        $this->addMetadata('deprecated_fields', [
            'shops' => 'Shop data is not available in the source files anymore, there is currently no replacement.',
        ]);

        $itemData = $this->resource;

        $type = $this->stripItemTypePrefix($itemData->type);

        $this->eagerLoadPortEquippedItems($itemData, $request);

        return [
            'uuid' => $this->item->uuid,
            'slug' => $this->item->slug,
            'name' => $itemData->name,
            'class_name' => $itemData->class_name,
            'classification' => $itemData->classification,
            'classification_label' => $itemData->classification_label,
            'description' => $this->getTranslation($itemData->item, $request),
            'size' => $itemData->size,
            'mass' => $this->extractNumeric($itemData, 'Mass'),
            $this->mergeWhen($itemData->rarity !== null, [
                'rarity' => $itemData->rarity,
            ]),
            'is_base_variant' => $itemData->base_id === null,
            'is_craftable' => $itemData->is_craftable,
            $this->mergeWhen($itemData->is_craftable, [
                'blueprint' => $this->isFullBlueprintMode($itemData)
                    ? $this->buildFullBlueprintPayload($itemData, $request)
                    : $this->buildBlueprintPayload($itemData, $request),
            ]),
            $this->mergeWhen(str_starts_with($itemData->classification ?? '', 'Ship.'), [
                'grade' => ItemData::formatGrade($itemData->grade, $itemData->classification),
                'class' => $itemData->class,
            ]),
            'description_data' => ItemDescriptionDataResource::collection($itemData->descriptionData),
            'manufacturer_description' => $itemData->getDescriptionDatum('Manufacturer'),
            'manufacturer' => $itemData->relationLoaded('manufacturer')
                ? new ManufacturerLinkResource($itemData->manufacturer)
                : null,
            'type' => $type,
            'type_label' => $itemData->type_label,
            'type_web_url' => $this->buildTypeWebUrl($type, $request),
            'sub_type' => $itemData->sub_type,
            'sub_type_label' => $itemData->sub_type_label,
            $this->mergeWhen(...$this->addAttachmentPosition($itemData)),
            $this->mergeWhen($this->isTurret($itemData), $this->addTurretData($itemData)),
            $this->mergeWhen(...$this->addSpecification($itemData)),

            'dimension' => new ItemDimensionResource($itemData),

            $this->mergeWhen($this->hasInStdItem($itemData, 'InventoryContainer'), [
                'inventory' => new ItemInventoryResource($this->extractFromStdItem($itemData, 'InventoryContainer')),
            ]),

            'tags' => $this->extractArray($itemData, 'Tags'),
            'required_tags' => $this->extractArray($itemData, 'RequiredTags'),
            'entity_tags' => $itemData->relationLoaded('entityTags')
                ? $itemData->entityTags->pluck('uuid')->values()->toArray()
                : [],
            'entity_tag_map' => $itemData->relationLoaded('entityTags')
                ? $itemData->entityTags->map(fn ($tag) => [
                    'uuid' => $tag->uuid,
                    'name' => $tag->name,
                ])->values()->toArray()
                : [],
            'interactions' => $this->extractArray($itemData, 'Interactions'),
            'ports' => ItemPortResource::collection($this->when($this->hasInStdItem($itemData, 'Ports'), $this->extractPorts($itemData))),
            $this->mergeWhen($this->hasInStdItem($itemData, 'ResourceContainer'), [
                'resource_container' => new ResourceContainerResource(
                    $this->extractFromStdItem($itemData, 'ResourceContainer'),
                    $itemData->relationLoaded('commodities') ? $itemData->commodities->keyBy('uuid') : null,
                ),
            ]),

            $this->mergeWhen($this->hasInStdItem($itemData, 'RadiationResistance'), [
                'radiation_resistance' => new RadiationResistanceResource($this->extractFromStdItem($itemData, 'RadiationResistance')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'TemperatureResistance'), [
                'temperature_resistance' => new TemperatureResistanceResource($this->extractFromStdItem($itemData, 'TemperatureResistance')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'GForceResistance'), [
                'gforce_resistance' => Arr::get($this->extractFromStdItem($itemData, 'GForceResistance'), 'Value'),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'HeatConnection'), [
                'heat' => new ItemHeatConnectionResource($this->extractFromStdItem($itemData, 'HeatConnection')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'Temperature'), [
                'temperature' => new ItemTemperatureResource($this->extractFromStdItem($itemData, 'Temperature')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'PowerConnection'), [
                'power' => new ItemPowerConnectionResource($this->extractFromStdItem($itemData, 'PowerConnection')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'Durability') && $this->extractFromStdItem($itemData, 'Durability.Health', 0) > 0, [
                'durability' => new ItemDurabilityResource($this->extractFromStdItem($itemData, 'Durability')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'Distortion'), [
                'distortion' => new ItemDistortionResource($this->extractFromStdItem($itemData, 'Distortion')),
            ]),
            $this->mergeWhen($this->hasInStdItem($itemData, 'ResourceNetwork'), [
                'resource_network' => new ResourceNetworkResource($itemData),
                'emission' => new ItemEmissionResource($this->extractFromStdItem($itemData, 'Emission')),
            ]),

            'shops' => [],
            'images' => $this->item->images ?? [],
            'uex_prices' => $this->expandUexPrices($itemData),
            $this->mergeWhen($itemData->base_id !== null && $itemData->relationLoaded('baseVariant'), fn () => [
                'base_variant' => new ItemLinkResource($itemData->baseVariant),
            ]),
            'variants' => $itemData->relationLoaded('variants')
                ? ItemLinkResource::collection(
                    $itemData->variants
                        ->filter(fn ($variant) => $variant->item !== null)
                )
                : [],
            $this->mergeWhen(
                $itemData->relationLoaded('setItems'),
                fn () => [
                    'related_items' => new RelatedItemsResource($itemData),
                ]
            ),
            $this->mergeWhen(
                $itemData->relationLoaded('installedOnVehicles'),
                fn () => [
                    'vehicles' => $itemData->installedOnVehicles
                        ->sortBy([
                            fn ($vd) => $vd->manufacturer?->name ?? '',
                            fn ($vd) => $vd->display_name ?? $vd->name,
                        ])
                        ->map(fn ($vd) => (new VehicleLinkResource($vd))->resolve())
                        ->values()
                        ->all(),
                ]
            ),
            'web_url' => $this->buildWebUrl($request),
            'link' => $this->buildApiUrl($request),
            'updated_at' => $itemData->updated_at,
            'version' => $itemData->relationLoaded('gameVersion')
                ? $itemData->gameVersion->code
                : null,
        ];
    }

    private function buildApiUrl(Request $request): string
    {
        return $this->urlWithVersion(
            route('items.show', ['identifier' => $this->item->uuid]),
            $request,
        );
    }

    /**
     * @return array<int, array{uuid: string, name: string, link: string}>
     */
    private function buildBlueprintPayload(ItemData $itemData, Request $request): array
    {
        return collect($itemData->blueprint)
            ->map(fn (array $blueprint): array => [
                'uuid' => $blueprint['uuid'],
                'name' => $blueprint['name'],
                'link' => $this->urlWithVersion(
                    route('blueprints.show', ['blueprint' => $blueprint['uuid']]),
                    $request
                ),
            ])
            ->values()
            ->all();
    }

    private function buildFullBlueprintPayload(ItemData $itemData, Request $request): array
    {
        $craftingBlueprints = $itemData->relationLoaded('craftingBlueprints')
            ? $itemData->getRelation('craftingBlueprints')
            : collect();

        return $craftingBlueprints
            ->map(fn (BlueprintData $blueprintData): array => (new BlueprintResource($blueprintData))->resolve())
            ->all();
    }

    private function isFullBlueprintMode(ItemData $itemData): bool
    {
        if (! $itemData->relationLoaded('craftingBlueprints')) {
            return false;
        }

        return $itemData->craftingBlueprints->first()?->relationLoaded('ingredients') ?? false;
    }

    /**
     * Eager load ItemData for all equipped items in ports to prevent N+1 queries.
     *
     * Only runs on the items.show route where equipped items are displayed.
     */
    private function eagerLoadPortEquippedItems(ItemData $itemData, Request $request): void
    {
        if (! $request->routeIs('items.show')) {
            return;
        }

        $ports = $this->extractPorts($itemData);
        if ($ports === []) {
            return;
        }

        $uuids = collect($ports)
            ->filter(fn (array $port) => ! empty($port['EquippedItem']))
            ->pluck('EquippedItem')
            ->unique()
            ->values()
            ->all();

        if ($uuids === []) {
            return;
        }

        $loaded = $this->eagerLoadPortItemData($uuids);
        request()->attributes->set('eager_loaded_port_items', $loaded);
    }

    protected function addSpecification(ItemData $itemData): array
    {
        $result = SpecificationRegistry::make()->resolve($itemData);

        if (! $result['has_match']) {
            return [false, []];
        }

        foreach ($result['deprecated'] as $deprecated) {
            $this->addMetadata('deprecated_fields', $deprecated);
        }

        return [
            true,
            fn () => $this->resolveSpecifications($result['specifications']),
        ];
    }

    private function resolveSpecifications(array $specifications): array
    {
        return array_map(
            static fn ($spec) => is_callable($spec) ? $spec() : $spec,
            $specifications
        );
    }

    protected function isTurret(ItemData $itemData): bool
    {
        return in_array($itemData->type, [
            'Turret',
            'TurretBase',
            'UtilityTurret',
            'MissileLauncher',
            'BombLauncher',
            'WeaponMount',
        ], true);
    }

    protected function addTurretData(ItemData $itemData): array
    {
        $mountName = 'max_mounts';
        if ($itemData->type === 'MissileLauncher') {
            $mountName = 'max_missiles';
        } elseif ($itemData->type === 'BombLauncher') {
            $mountName = 'max_bombs';
        }

        $ports = collect($this->extractPorts($itemData));

        return [
            $mountName => $ports->count(),
            'min_size' => $ports->min('MinSize') ?? $ports->min('min_size'),
            'max_size' => $ports->max('MaxSize') ?? $ports->max('max_size'),
        ];
    }

    private function addAttachmentPosition(ItemData $itemData): array
    {
        if ($itemData->type !== 'WeaponAttachment' || $itemData->name === '<= PLACEHOLDER =>') {
            return [false, []];
        }

        return [
            true,
            fn () => [
                'position' => match ($itemData->sub_type) {
                    'Magazine' => 'Magazine Well',
                    'Barrel' => 'Barrel',
                    'IronSight' => 'Optic',
                    'Utility' => 'Utility',
                    'BottomAttachment' => 'Underbarrel',
                    default => $itemData->sub_type,
                },
            ],
        ];
    }

    private function getTranslation(Item $item, Request $request): array|string|null
    {
        return TranslationResolver::resolve($item, $request);
    }

    private function buildWebUrl(Request $request): string
    {
        return $this->urlWithVersion(
            route('web.items.show', ['item' => $this->item->slug ?? $this->item->uuid]),
            $request,
        );
    }

    private function buildTypeWebUrl(?string $type, Request $request): ?string
    {
        if ($type === null || $type === '') {
            return null;
        }

        return $this->urlWithVersion(
            route('web.items.index', ['filter' => ['type' => $type]]),
            $request,
        );
    }

    private function expandUexPrices(ItemData $itemData): array
    {
        return $this->expandPrices((array) ($itemData->uex_prices ?? []));
    }
